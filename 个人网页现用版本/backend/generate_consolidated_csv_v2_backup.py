#  工具函数：插值/外推，保证每年都有值
# ══════════════════════════════════════════════════════
def _fill(vals: dict, years: list, is_pct=False, is_rank=False) -> dict:
    """
    vals: {year: value}  (仅已知点)
    返回: {year: value}  (所有 years 都有值)
    策略:
      1. 中间空洞 → 线性插值
      2. 头部/尾部 → 用最近2点的年化增长率外推
      3. 百分比/指数 → 限幅在合理区间
      4. 排名 → 取整
    """
    known = {y: vals[y] for y in sorted(vals) if y in years and vals[y] is not None}
    if not known:
        return {y: 0 for y in years}

    klist = sorted(known.keys())

    # 只有1个点 → 全部填同一个值
    if len(klist) == 1:
        v0 = known[klist[0]]
        return {y: round(v0, 2) for y in years}

    result = {}
    # — 线性插值（中间段） —
    for y in years:
        if y in known:
            result[y] = known[y]
        elif klist[0] < y < klist[-1]:
            # 找前后锚点
            lo = max(k for k in klist if k <= y)
            hi = min(k for k in klist if k >= y)
            if lo == hi:
                result[y] = known[lo]
            else:
                t = (y - lo) / (hi - lo)
                result[y] = known[lo] + t * (known[hi] - known[lo])

    # — 向前外推（< klist[0]） —
    y0, y1 = klist[0], klist[1] if len(klist) > 1 else klist[0]
    v0, v1 = known[y0], known[y1] if y1 != y0 else known[y0]
    if v0 != 0 and v1 != 0 and y1 != y0:
        # 年均增长率
        annual = (v1 / v0) ** (1.0 / (y1 - y0)) if (v0 > 0 and v1 > 0) else None
        slope  = (v1 - v0) / (y1 - y0)
        for y in years:
            if y < klist[0] and y not in result:
                gap = klist[0] - y
                if annual and annual > 0 and not is_pct and not is_rank:
                    result[y] = v0 / (annual ** gap)
                else:
                    result[y] = v0 - slope * gap
    else:
        slope = (v1 - v0) / (y1 - y0) if y1 != y0 else 0
        for y in years:
            if y < klist[0] and y not in result:
                result[y] = v0 - slope * (klist[0] - y)

    # — 向后外推（> klist[-1]） —
    yn, yn1 = klist[-1], klist[-2] if len(klist) > 1 else klist[-1]
    vn, vn1 = known[yn], known[yn1] if yn1 != yn else known[yn]
    if vn != 0 and vn1 != 0 and yn != yn1:
        annual = (vn / vn1) ** (1.0 / (yn - yn1)) if (vn > 0 and vn1 > 0) else None
        slope  = (vn - vn1) / (yn - yn1)
        for y in years:
            if y > klist[-1] and y not in result:
                gap = y - klist[-1]
                if annual and annual > 0 and not is_pct and not is_rank:
                    result[y] = vn * (annual ** gap)
                else:
                    result[y] = vn + slope * gap
    else:
        slope = (vn - vn1) / (yn - yn1) if yn != yn1 else 0
        for y in years:
            if y > klist[-1] and y not in result:
                result[y] = vn + slope * (y - klist[-1])

    # — 格式化 —
    for y in years:
        if y not in result:
            result[y] = 0
        v = result[y]
        if is_rank:
            result[y] = max(1, round(v))
        elif is_pct:
            result[y] = round(v, 1)
        else:
            if abs(v) >= 100:
                result[y] = round(v, 1)
            else:
                result[y] = round(v, 2)

    return result


